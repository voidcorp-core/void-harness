#!/usr/bin/env node
// Generate docs/CHEATSHEET.md from the graph model.
//
// The list of entries is never written by hand: it comes from model.json, the
// same catalogue `status`, `doctor` and the graph all read. Only the editorial
// layer lives in docs/cheatsheet-taxonomy.json — which domain a skill belongs
// to, and what a hook does, because hook `.sh` files are generic adapters that
// describe nothing.
//
// test/cheatsheet/ fails when the two disagree in either direction: an entry in
// the model with no group, or a group naming something the model does not have.
// That is what keeps this page from becoming the fourth stale list.
//
// Usage: node scripts/build-cheatsheet.mjs [--check]
// Exported: renderCheatsheet(model, taxonomy) — pure, unit-tested.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MODEL = resolve(ROOT, 'packages/harness-graph/model.json');
const TAXONOMY = resolve(ROOT, 'docs/cheatsheet-taxonomy.json');
const OUTPUT = resolve(ROOT, 'docs/CHEATSHEET.md');

/** Nodes of one type, sorted by name for a stable diff. */
function ofType(model, type) {
  return (model.nodes ?? [])
    .filter((node) => (node.type ?? node.kind) === type)
    .slice()
    .sort((a, b) => (a.name ?? '').localeCompare(b.name ?? ''));
}

function byName(nodes) {
  return new Map(nodes.map((node) => [node.name, node]));
}

/**
 * Enough of a description to be useful, little enough to stay scannable.
 *
 * Sentence-boundary alone is not it: several skills open on a three-word
 * fragment ("Tidy-First.", "Ports + adapters.") that tells a newcomer nothing.
 * So sentences are added until the line carries its weight, then stopped.
 */
const MIN_USEFUL = 60;
const MAX_LENGTH = 180;

function short(description) {
  const text = (description ?? '').replace(/\s+/g, ' ').trim();
  if (text === '') return '';

  const sentences = text.match(/[^.!?]+[.!?]?/g) ?? [text];
  let out = '';
  for (const sentence of sentences) {
    if (out.length >= MIN_USEFUL) break;
    if (out.length + sentence.length > MAX_LENGTH && out !== '') break;
    out += sentence;
  }
  out = out.trim();
  return out.length > MAX_LENGTH ? `${out.slice(0, MAX_LENGTH - 1).trimEnd()}…` : out;
}

function table(rows) {
  return ['| | |', '|---|---|', ...rows].join('\n');
}

export function renderCheatsheet(model, taxonomy) {
  const skills = ofType(model, 'skill');
  const coreSkills = byName(skills.filter((skill) => skill.pack == null));
  const packSkills = skills.filter((skill) => skill.pack != null);
  const hooks = byName(ofType(model, 'hook'));
  const agents = byName(ofType(model, 'agent'));
  const commands = ofType(model, 'command');
  const packs = ofType(model, 'pack');

  const out = [];
  out.push('# void-harness cheat sheet');
  out.push('');
  out.push('Everything the harness installs, and how each piece fires.');
  out.push('');
  out.push(
    '**Generated from the catalogue** — `node scripts/build-cheatsheet.mjs`. Do not edit this file; edit the skill, or `docs/cheatsheet-taxonomy.json` for the grouping.',
  );
  out.push('');
  out.push(
    `**Skills advise, agents audit, hooks enforce.** The doctrine holds because the last layer is not optional: ${coreSkills.size} core skills, ${packSkills.length} pack skills, ${agents.size} agents, ${hooks.size} hooks.`,
  );
  out.push('');
  out.push('---');
  out.push('');

  out.push('## Skills');
  out.push('');
  out.push(
    'Loaded automatically when what you are doing matches their description. You can also call one by name when you want that one specifically.',
  );
  out.push('');
  for (const group of taxonomy.skillGroups) {
    out.push(`### ${group.title}`);
    out.push('');
    out.push(group.blurb);
    out.push('');
    out.push(
      table(
        group.skills.map((name) => {
          const skill = coreSkills.get(name);
          return `| \`${name}\` | ${short(skill?.description)} |`;
        }),
      ),
    );
    out.push('');
  }

  out.push('### Stack packs');
  out.push('');
  out.push('Activated per project with `npx voidharness add <pack>`.');
  out.push('');
  for (const pack of packs) {
    const owned = packSkills.filter((skill) => skill.pack === pack.name);
    if (owned.length === 0) continue;
    out.push(`**${pack.name}** — ${owned.length} skills`);
    out.push('');
    out.push(table(owned.map((skill) => `| \`${skill.name}\` | ${short(skill.description)} |`)));
    out.push('');
  }

  out.push('---');
  out.push('');
  out.push('## Agents');
  out.push('');
  out.push('Fresh context, invoked by a skill or by name.');
  out.push('');
  for (const group of taxonomy.agentGroups) {
    out.push(`### ${group.title}`);
    out.push('');
    out.push(group.blurb);
    out.push('');
    out.push(
      table(group.agents.map((name) => `| \`${name}\` | ${short(agents.get(name)?.description)} |`)),
    );
    out.push('');
  }

  const grouped = new Set(taxonomy.agentGroups.flatMap((group) => group.agents));
  const specialists = [...agents.keys()].filter((name) => !grouped.has(name));
  if (specialists.length > 0) {
    out.push('### Domain specialists');
    out.push('');
    out.push('Invoked during review, each in its own context, each returning the same contract.');
    out.push('');
    out.push(table(specialists.map((name) => `| \`${name}\` | ${short(agents.get(name)?.description)} |`)));
    out.push('');
  }

  out.push('---');
  out.push('');
  out.push('## Hooks');
  out.push('');
  out.push('The automatic floor. They fire on the tool call, before the write lands, and they are not optional.');
  out.push('');
  for (const group of taxonomy.hookGroups) {
    out.push(`### ${group.title}`);
    out.push('');
    out.push(group.blurb);
    out.push('');
    out.push(table(Object.entries(group.hooks).map(([name, text]) => `| \`${name}\` | ${text} |`)));
    out.push('');
  }

  if (commands.length > 0) {
    out.push('---');
    out.push('');
    out.push('## Commands');
    out.push('');
    out.push('The surface no sentence can trigger, because it reports or changes state.');
    out.push('');
    out.push(table(commands.map((command) => `| \`${command.name}\` | ${short(command.description)} |`)));
    out.push('');
  }

  return `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

const model = JSON.parse(readFileSync(MODEL, 'utf8'));
const taxonomy = JSON.parse(readFileSync(TAXONOMY, 'utf8'));
const rendered = renderCheatsheet(model, taxonomy);

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(OUTPUT, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== rendered) {
    process.stderr.write('cheatsheet is stale — run `pnpm cheatsheet:build` and commit docs/CHEATSHEET.md.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('cheatsheet:check — in sync.\n');
  }
} else {
  writeFileSync(OUTPUT, rendered);
  process.stdout.write(`cheatsheet:build — wrote ${OUTPUT.replace(`${ROOT}/`, '')}\n`);
}
