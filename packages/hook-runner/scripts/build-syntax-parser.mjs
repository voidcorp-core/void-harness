// A compressed, inert payload keeps the parser out of the parent process and
// preserves the single-file hook distribution. Only the isolated child loads it.
// esbuild 0.28: https://esbuild.github.io/api/#global-name and #legal-comments.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const packageRoot = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: packageRoot,
  entryPoints: ['src/enforcement/syntax-analysis.ts'],
  bundle: true,
  platform: 'node',
  format: 'iife',
  globalName: 'harnessSyntaxParser',
  target: 'node22',
  minify: true,
  legalComments: 'inline',
  write: false,
});
const compressed = gzipSync(result.outputFiles[0].contents, { level: 9 }).toString('base64');
const manifest = createRequire(import.meta.url).resolve('@babel/parser/package.json');
const license = readFileSync(join(dirname(manifest), 'LICENSE'), 'utf8');
writeFileSync(new URL('../src/enforcement/syntax-parser.generated.ts', import.meta.url),
  '// Generated by scripts/build-syntax-parser.mjs. Do not edit.\n'
  + `/*! @babel/parser (MIT)\n${license}*/\n`
  + `export const SYNTAX_PARSER_GZIP = '${compressed}';\n`);
